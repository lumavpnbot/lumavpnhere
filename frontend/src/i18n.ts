const DICTS: Record<Lang, Record<Key, string>> = { ru, en }

export type TKey = Key

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = DICTS[lang][key] ?? ru[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export function useT() {
  const lang = useAppStore((s) => s.lang)
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

export function useLang() {
  return useAppStore((s) => s.lang)
}

/** Склонения: ru по трём формам, en по двум. */
export function plural(lang: Lang, n: number, forms: { ru: [string, string, string]; en: [string, string] }) {
  if (lang === 'en') return n === 1 ? forms.en[0] : forms.en[1]
  const m10 = n % 10
  const m100 = n % 100
  if (m10 === 1 && m100 !== 11) return forms.ru[0]
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms.ru[1]
  return forms.ru[2]
}
